/**
 * Reads the recipe table from the vault note "Crafting (DH)" and writes scripts/recipes-data.mjs.
 *
 *   node tools/recipes.mjs
 *
 * Where the vault is: tools/vault.txt (one line, the vault folder; not in git) or MBF_VAULT.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseRecipeTable, PRODUCT_TYPES } from "../scripts/recipes.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const NOTE = path.join("0_Daggerheart Mechaniken", "Hausregeln", "Crafting (DH).md");
const OUT = path.join(ROOT, "scripts", "recipes-data.mjs");

function vaultFolder() {
  const file = path.join(ROOT, "tools", "vault.txt");
  const fromFile = fs.existsSync(file) ? fs.readFileSync(file, "utf8").trim() : "";
  const folder = process.env.MBF_VAULT || fromFile;
  if (!folder) throw new Error("Where is the vault? Put its folder into tools/vault.txt.");
  return folder;
}

const source = path.join(vaultFolder(), NOTE);
const recipes = parseRecipeTable(fs.readFileSync(source, "utf8"));
const header = `/**
 * GENERATED by tools/recipes.mjs from the vault note "Crafting (DH)", section "Rezepte".
 * Do not edit by hand: change the note and run \`npm run recipes\`.
 */
`;
fs.writeFileSync(OUT, `${header}export const RECIPES = ${JSON.stringify(recipes, null, 2)};\n`, "utf8");

const byType = Object.keys(PRODUCT_TYPES).map(t => `${recipes.filter(r => r.type === t).length} ${PRODUCT_TYPES[t].label}`);
console.log(`Read ${recipes.length} recipes (${byType.join(", ")}) -> scripts/recipes-data.mjs`);
